// Generates website data from the repository so the site never drifts from the code:
//   snippets.json      code regions extracted from compiled Java/YAML sources (// @snippet:id ... // @end)
//   docs.json          docs metadata (title, description, table of contents) from MDX frontmatter + headings
//   search-index.json  static search index (titles, headings, text)
//   project.json       version and repository facts from gradle.properties
//   compatibility.json copied from docs/compatibility.json
//   changelog.json     parsed from CHANGELOG.md
//   releases.json      GitHub Releases (best effort; empty when the repository has no releases or is offline)
//   api.json           API manifest generated by the Gradle apidoc doclet (build/api/api-manifest.json)
// It also writes public/llms.txt and public/llms-full.txt for AI tools.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import GithubSlugger from "github-slugger";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..");
const repo = join(site, "..");
const out = join(site, "src", "generated");
const publicDir = join(site, "public");
mkdirSync(out, { recursive: true });

const REPOSITORY = "crownalonedev/bloom";
const write = (name, data) => writeFileSync(join(out, name), JSON.stringify(data, null, 2) + "\n");

function walk(dir, filter, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const entry of readdirSync(dir)) {
    if (entry === "build" || entry === "node_modules" || entry.startsWith(".")) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, filter, acc);
    else if (filter(full)) acc.push(full);
  }
  return acc;
}

// ---- snippets --------------------------------------------------------------------------------------------------
function dedent(lines) {
  const indents = lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length);
  const min = indents.length ? Math.min(...indents) : 0;
  return lines.map((l) => l.slice(min)).join("\n").replace(/\s+$/, "");
}

const snippets = {};
const sourceFiles = walk(join(repo, "bloom-examples"), (f) => /\.(java|ya?ml|kts)$/.test(f));
for (const file of sourceFiles) {
  const lines = readFileSync(file, "utf8").split(/\r?\n/);
  let open = null;
  for (let i = 0; i < lines.length; i++) {
    const start = lines[i].match(/^\s*(?:\/\/|#)\s*@snippet:([\w.-]+)\s*$/);
    if (start) {
      if (open) throw new Error(`Nested snippet in ${file}:${i + 1}`);
      open = { id: start[1], from: i + 1, lines: [] };
      continue;
    }
    if (/^\s*(?:\/\/|#)\s*@end\s*$/.test(lines[i])) {
      if (!open) throw new Error(`@end without @snippet in ${file}:${i + 1}`);
      if (snippets[open.id]) throw new Error(`Duplicate snippet id ${open.id}`);
      snippets[open.id] = {
        code: dedent(open.lines.filter((l) => !/@snippet-hide/.test(l))),
        source: relative(repo, file).replaceAll("\\", "/") + `#L${open.from + 1}-L${i}`,
      };
      open = null;
      continue;
    }
    if (open) open.lines.push(lines[i]);
  }
  if (open) throw new Error(`Unclosed snippet ${open.id} in ${file}`);
}
write("snippets.json", snippets);

// ---- docs metadata and search index ------------------------------------------------------------------------------
const docsDir = join(site, "src", "content", "docs");
const docs = [];
const search = [];
const llmsFull = [];
for (const file of readdirSync(docsDir).filter((f) => f.endsWith(".mdx")).sort()) {
  const slug = file.replace(/\.mdx$/, "");
  const raw = readFileSync(join(docsDir, file), "utf8");
  const fm = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!fm) throw new Error(`${file} needs frontmatter`);
  const meta = Object.fromEntries(
    fm[1].split(/\r?\n/).map((l) => l.match(/^(\w+):\s*(.*)$/)).filter(Boolean)
      .map((m) => [m[1], m[2].replace(/^["']|["']$/g, "")]),
  );
  if (!meta.title || !meta.description) throw new Error(`${file} needs title and description`);
  const body = raw.slice(fm[0].length);
  const slugger = new GithubSlugger();
  const toc = [];
  const sections = [{ heading: meta.title, anchor: "", text: [] }];
  let inFence = false;
  for (const line of body.split(/\r?\n/)) {
    if (/^```/.test(line)) {
      inFence = !inFence;
      continue;
    }
    const heading = !inFence && line.match(/^(#{2,3})\s+(.+)$/);
    if (heading) {
      const text = heading[2].replace(/`/g, "").trim();
      const anchor = slugger.slug(text);
      toc.push({ depth: heading[1].length, text, anchor });
      sections.push({ heading: text, anchor, text: [] });
      continue;
    }
    if (inFence || /^(import|export)\s/.test(line)) continue;
    const plain = line.replace(/<[^>]+>/g, " ").replace(/[*_`>#|[\]()]/g, " ").replace(/\s+/g, " ").trim();
    if (plain) sections[sections.length - 1].text.push(plain);
  }
  docs.push({ slug, title: meta.title, description: meta.description, toc });
  for (const section of sections) {
    search.push({
      slug,
      page: meta.title,
      heading: section.heading,
      anchor: section.anchor,
      text: section.text.join(" ").slice(0, 600),
    });
  }
  llmsFull.push(`# ${meta.title}\n\nURL: /docs/${slug}\n\n${meta.description}\n\n${body.trim()}\n`);
}
write("docs.json", docs);
write("search-index.json", search);

// ---- project facts -------------------------------------------------------------------------------------------------
const gradleProps = readFileSync(join(repo, "gradle.properties"), "utf8");
const version = gradleProps.match(/^version=(.+)$/m)?.[1]?.trim() ?? "unknown";
const group = gradleProps.match(/^group=(.+)$/m)?.[1]?.trim() ?? "unknown";
write("project.json", { version, group, repository: `https://github.com/${REPOSITORY}` });
write("compatibility.json", JSON.parse(readFileSync(join(repo, "docs", "compatibility.json"), "utf8")));

// ---- changelog -----------------------------------------------------------------------------------------------------
const changelog = [];
const changelogFile = join(repo, "CHANGELOG.md");
if (existsSync(changelogFile)) {
  let current = null;
  for (const line of readFileSync(changelogFile, "utf8").split(/\r?\n/)) {
    const release = line.match(/^## \[?([^\]\s]+)\]?(?:\s+-\s+(.+))?/);
    if (release) {
      current = { version: release[1], date: release[2] ?? null, groups: [] };
      changelog.push(current);
    } else if (current && line.startsWith("### ")) {
      current.groups.push({ title: line.slice(4).trim(), items: [] });
    } else if (current && /^[-*] /.test(line)) {
      if (!current.groups.length) current.groups.push({ title: "Changes", items: [] });
      current.groups[current.groups.length - 1].items.push(line.slice(2).trim());
    }
  }
}
write("changelog.json", changelog);

// ---- releases (best effort) ---------------------------------------------------------------------------------------
let releases = { available: false, reason: "not fetched", releases: [] };
if (process.env.BLOOM_SKIP_RELEASES !== "1") {
  try {
    const response = await fetch(`https://api.github.com/repos/${REPOSITORY}/releases?per_page=20`, {
      headers: { Accept: "application/vnd.github+json", "User-Agent": "bloom-website-build" },
      signal: AbortSignal.timeout(5000),
    });
    if (response.ok) {
      const list = await response.json();
      releases = {
        available: true,
        fetchedAt: new Date().toISOString(),
        releases: list.filter((r) => !r.draft).map((r) => ({
          tag: r.tag_name,
          name: r.name || r.tag_name,
          prerelease: r.prerelease,
          publishedAt: r.published_at,
          url: r.html_url,
          body: r.body ?? "",
          assets: r.assets.map((a) => ({ name: a.name, url: a.browser_download_url, size: a.size })),
        })),
      };
    } else {
      releases.reason = `GitHub API returned ${response.status} (the repository may not be public yet)`;
    }
  } catch (error) {
    releases.reason = `GitHub API unreachable: ${error.message}`;
  }
}
write("releases.json", releases);

// ---- API manifest ---------------------------------------------------------------------------------------------------
const manifest = join(repo, "build", "api", "api-manifest.json");
if (existsSync(manifest)) {
  const api = JSON.parse(readFileSync(manifest, "utf8"));
  write("api.json", { available: true, ...api });
  mkdirSync(publicDir, { recursive: true });
  writeFileSync(join(publicDir, "api-manifest.json"), JSON.stringify(api) + "\n");
} else {
  write("api.json", { available: false, reason: "Run ./gradlew apiManifest to generate build/api/api-manifest.json", modules: [] });
}

// ---- llms.txt ------------------------------------------------------------------------------------------------------
mkdirSync(publicDir, { recursive: true });
const llms = [
  "# Bloom Framework",
  "",
  `> Cross-version Minecraft plugin framework (Bukkit/Spigot 1.7.10-1.8.9 and Paper 1.21.1-26.3.x). Version ${version}, Maven group ${group}.`,
  "",
  "Read /llms-full.txt for all documentation in one file and /api-manifest.json for every public type and method.",
  "Only use methods listed in the API manifest; do not invent APIs. Check capabilities before version-specific features.",
  "",
  "## Docs",
  ...docs.map((d) => `- [${d.title}](/docs/${d.slug}): ${d.description}`),
  "",
];
writeFileSync(join(publicDir, "llms.txt"), llms.join("\n"));
writeFileSync(join(publicDir, "llms-full.txt"), `# Bloom Framework documentation (version ${version})\n\n` + llmsFull.join("\n---\n\n"));

console.log(`content: ${Object.keys(snippets).length} snippets, ${docs.length} docs, ${search.length} search entries, ` +
  `${changelog.length} changelog entries, releases ${releases.available ? releases.releases.length : "unavailable"}`);
